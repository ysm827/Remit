def get_modeler_prompt(task_purpose: TaskPurpose = "modeling") -> str:
    if task_purpose == "numerical_verification":
        return NUMERICAL_MODELER_PROMPT
    if task_purpose != "modeling":
        raise ValueError("未知任务目的")
    return MODELER_PROMPT


